function mapToCodePoint(code) {
  if (Object.prototype.hasOwnProperty.call(GBK_TO_UNICODE, code)) {
    return GBK_TO_UNICODE[code];
  }
  return 0xFFFD;
}

export function decode(bytes) {
  let result = '';
  let i = 0;
  while (i < bytes.length) {
    const b0 = bytes[i];
    if (b0 < 0x80) {
      result += String.fromCharCode(b0);
      i += 1;
    } else {
      if (i + 1 >= bytes.length) {
        result += '\uFFFD';
        i += 1;
      } else {
        const b1 = bytes[i + 1];
        const gbkCode = b0 * 0x100 + b1;
        const cp = mapToCodePoint(gbkCode);
        result += String.fromCharCode(cp);
        i += 2;
      }
    }
  }
  return result;
}
